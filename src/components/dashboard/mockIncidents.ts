// To ensure statistically rich metrics matching business needs (e.g., 124 incidents in 01-14 Oct),
// we supplement with deterministic distributed incidents
export function generateIncidentsPool(): IncidentRecord[] {
  const baseList = [...MOCK_INCIDENTS]
  
  // Seed extra incidents deterministically across dates to match SaaS volume
  const assetsPool = [
    { name: "Thang máy B2", nameEn: "Elevator B2", id: "AST-ELEV-02", cat: "electrical" as const },
    { name: "Bơm áp lực #1", nameEn: "Pressure Pump #1", id: "AST-PUMP-01", cat: "plumbing" as const },
    { name: "Chiller #02", nameEn: "Chiller #02", id: "AST-HVAC-02", cat: "hvac" as const },
    { name: "Quạt PCCC", nameEn: "Fire Safety Fan", id: "AST-FIRE-01", cat: "fire_safety" as const },
    { name: "Máy phát điện", nameEn: "Generator", id: "AST-GEN-01", cat: "electrical" as const },
  ]

  // Add distributed incidents for October 1-14 so total is ~124
  for (let day = 1; day <= 14; day++) {
    const dayStr = day < 10 ? `0${day}` : `${day}`
    const date = `2026-10-${dayStr}`
    
    // 6-8 incidents per day
    const countForDay = (day % 3 === 0 ? 8 : (day % 2 === 0 ? 7 : 6))
    for (let i = 0; i < countForDay; i++) {
      const asset = assetsPool[(day + i) % assetsPool.length]
      const hour = 8 + ((i * 2 + day) % 10)
      const minute = (i * 17) % 60
      const hourStr = hour < 10 ? `0${hour}` : `${hour}`
      const minStr = minute < 10 ? `0${minute}` : `${minute}`
      
      const isBreached = (day === 4 && i === 2) || (day === 11 && i === 1) || (day === 8 && i === 3)
      const repairTime = 30 + ((day * 7 + i * 11) % 35) // 30-65 mins, avg ~45
      const partsCost = 40 + ((day * 13 + i * 29) % 220) // parts cost
      
      baseList.push({
        id: `WO-${1050 + day * 10 + i}`,
        title: `Bảo trì đột xuất ${asset.name} - Hệ thống con #${i + 1}`,
        titleEn: `Ad-hoc Service ${asset.nameEn} - Subsystem #${i + 1}`,
        assetId: asset.id,
        assetName: asset.name,
        assetNameEn: asset.nameEn,
        category: asset.cat,
        location: `Khu phức hợp Vận hành - Trạm ${i + 1}`,
        locationEn: `Operational Facility - Station ${i + 1}`,
        createdAt: date,
        timestamp: `${date}T${hourStr}:${minStr}:00`,
        urgency: i === 0 && day === 14 ? "urgent" : i % 3 === 0 ? "high" : "medium",
        status: day === 14 && i < 2 ? "in_progress" : "completed",
        slaMet: !isBreached,
        repairTimeMinutes: repairTime,
        partsCost,
        timeAgo: `${14 - day} ngày trước`,
        timeAgoEn: `${14 - day} days ago`,
      })
    }
  }

  // Also add some incidents in late September for 30-day range
  for (let day = 15; day <= 30; day++) {
    const dayStr = `${day}`
    const date = `2026-09-${dayStr}`
    for (let i = 0; i < 4; i++) {
      const asset = assetsPool[(day + i) % assetsPool.length]
      baseList.push({
        id: `WO-${900 + day * 4 + i}`,
        title: `Kiểm tra định kỳ ${asset.name} - Điểm kiểm #${i + 1}`,
        titleEn: `Inspection for ${asset.nameEn} - Checkpoint #${i + 1}`,
        assetId: asset.id,
        assetName: asset.name,
        assetNameEn: asset.nameEn,
        category: asset.cat,
        location: `Tòa A/B - Phân khu kỹ thuật`,
        locationEn: `Block A/B - Technical Zone`,
        createdAt: date,
        timestamp: `${date}T10:00:00`,
        urgency: "medium",
        status: "completed",
        slaMet: !(i === 3 && day % 4 === 0),
        repairTimeMinutes: 35 + ((day + i) % 25),
        partsCost: 35 + ((day * 7 + i * 19) % 150),
        timeAgo: `${14 + (30 - day)} ngày trước`,
        timeAgoEn: `${14 + (30 - day)} days ago`,
      })
    }
  }

  return baseList
}

