/**
 * Nested key lookup with parameter interpolation.
 * e.g., t("assets.selectedCount", { count: 3 }) => "Đã chọn 3 tài sản" or "3 assets selected"
 */
export function getTranslation(
  lang: Language,
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = translations[lang] ?? translations.vi
  const parts = key.split(".")
  let current: any = dict

  for (const part of parts) {
    if (current && typeof current === "object" && part in current) {
      current = current[part]
    } else {
      // Fallback to vi if not found in current lang
      let fallbackCurrent: any = translations.vi
      for (const fbPart of parts) {
        if (
          fallbackCurrent &&
          typeof fallbackCurrent === "object" &&
          fbPart in fallbackCurrent
        ) {
          fallbackCurrent = fallbackCurrent[fbPart]
        } else {
          fallbackCurrent = undefined
          break
        }
      }
      if (typeof fallbackCurrent === "string") {
        current = fallbackCurrent
      } else {
        return key // Return key if not found
      }
      break
    }
  }

  if (typeof current !== "string") {
    return key
  }

  if (params) {
    return current.replace(/\{(\w+)\}/g, (_, match) => {
      return match in params ? String(params[match]) : `{${match}}`
    })
  }

  return current
}

/**
 * Universal bilingual accessor for localized entity fields:
 * looks up field_en or field_vi based on active language.
 */
export function getLocalizedField<T extends Record<string, any>>(
  item: T,
  field: string,
  lang: Language
): string {
  const key = `${field}_${lang}`
  if (key in item && typeof item[key] === "string") {
    return item[key]
  }
  const fallback = `${field}_vi`
  if (fallback in item && typeof item[fallback] === "string") {
    return item[fallback]
  }
  return item[field] ?? ""
}
